void solve() {
    int n, ops = 0;
    string s;
    cin >> n;
    cin >> s;

    for (int i = 0; i < n/2; i++) {
        if (s[i] != s[n - i - 1]) {
            ops++;
        } else {
            break;
        }
    }
    
    cout << n - 2 * ops << '\n';
}


